package org.firstinspires.ftc.teamcode.common.OnlyCode;

public class ShooterSolution {
    double speed;
    double angle;

    public ShooterSolution() {
    }

    public ShooterSolution(double speed, double angle) {
        this.speed = speed;
        this.angle = angle;
    }

    public double getSpeed() {
        return speed;
    }

    public void setSpeed(double speed) {
        this.speed = speed;
    }

    public double getAngle() {
        return angle;
    }

    public void setAngle(double angle) {
        this.angle = angle;
    }
}
