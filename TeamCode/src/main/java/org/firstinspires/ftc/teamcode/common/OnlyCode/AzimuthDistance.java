package org.firstinspires.ftc.teamcode.common.OnlyCode;

public class AzimuthDistance {
     double azimuth ;
     double distance;

    public AzimuthDistance() {
    }

    public AzimuthDistance(double azimuth, double distance) {
        this.azimuth = azimuth;
        this.distance = distance;
    }

    public double getAzimuth() {
        return azimuth;
    }

    public double getDistance() {
        return distance;
    }
}
